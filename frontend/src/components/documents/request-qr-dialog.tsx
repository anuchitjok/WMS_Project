'use client';

// On-screen request QR (plan P5 5.3): the warehouse shows it at handover so the
// requester can scan and confirm receipt on their phone — printing is optional.
import { useEffect, useState } from 'react';
import Link from 'next/link';
import { Copy, ExternalLink, QrCode } from 'lucide-react';
import { toast } from 'sonner';
import { Button } from '@/components/ui/button';
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Skeleton } from '@/components/ui/skeleton';
import { documentsRefApi, refPagePath, type RefQr } from '@/lib/api-documents';
import { getT, useT } from '@/i18n';

/** QR image + link for one request. Loads when mounted. */
export function RequestQrPanel({ refNumber }: { refNumber: string }) {
  const { m, t } = useT();
  const Q = m.documents.qr;
  const [qr, setQr] = useState<RefQr | null>(null);
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    let alive = true;
    setQr(null);
    setFailed(false);
    documentsRefApi.qr(refNumber).then((r) => { if (alive) setQr(r); }).catch(() => { if (alive) setFailed(true); });
    return () => { alive = false; };
  }, [refNumber]);

  async function copy() {
    if (!qr) return;
    try { await navigator.clipboard.writeText(qr.url); toast.success(getT().m.documents.qr.copied); } catch { /* clipboard blocked */ }
  }

  return (
    <div className="flex flex-col items-center gap-3">
      <div className="w-56 h-56 sm:w-64 sm:h-64 rounded-xl border border-slate-200 bg-white p-2 flex items-center justify-center">
        {qr ? (
          // SVG generated by the API (bwip-js) from our own URL — safe to inline.
          <div className="w-full h-full [&>svg]:w-full [&>svg]:h-full" aria-label={t(Q.title, { ref: refNumber })} role="img"
            dangerouslySetInnerHTML={{ __html: qr.svg }} />
        ) : failed ? (
          <p className="text-sm text-slate-500 text-center px-4">{Q.loadFailed}</p>
        ) : (
          <Skeleton className="w-full h-full" />
        )}
      </div>
      <p className="font-mono text-lg font-semibold text-slate-900">{refNumber}</p>
      <p className="text-sm text-slate-500 text-center max-w-sm">{Q.hint}</p>
      <div className="flex flex-wrap justify-center gap-2">
        <Button variant="outline" size="sm" onClick={copy} disabled={!qr}><Copy className="h-3.5 w-3.5" />{Q.copy}</Button>
        <Link href={refPagePath(refNumber)}>
          <Button variant="outline" size="sm"><ExternalLink className="h-3.5 w-3.5" />{Q.open}</Button>
        </Link>
      </div>
    </div>
  );
}

/** "Show QR" button that opens the QR in a dialog. */
export function RequestQrButton({ refNumber, size = 'sm', className }: { refNumber: string; size?: 'sm' | 'default'; className?: string }) {
  const { m, t } = useT();
  const [open, setOpen] = useState(false);
  return (
    <>
      <Button variant="outline" size={size} className={className} onClick={() => setOpen(true)}>
        <QrCode className="h-3.5 w-3.5" />{m.documents.qr.button}
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="max-w-md">
          <DialogHeader>
            <DialogTitle>{t(m.documents.qr.title, { ref: refNumber })}</DialogTitle>
            <DialogDescription className="sr-only">{m.documents.qr.hint}</DialogDescription>
          </DialogHeader>
          {open && <RequestQrPanel refNumber={refNumber} />}
        </DialogContent>
      </Dialog>
    </>
  );
}
