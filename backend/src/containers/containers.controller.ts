import { Body, Controller, Delete, Get, Param, Patch, Post, Query, UseGuards } from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiTags } from '@nestjs/swagger';
import { UserRole } from '@prisma/client';
import { ContainersService } from './containers.service';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { RolesGuard } from '../auth/guards/roles.guard';
import { Roles } from '../auth/decorators/roles.decorator';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import {
  CreateContainerDto, MergeContainerDto, MoveContainerDto, PackItemsDto, SplitContainerDto, UpdateContainerDto,
} from './containers.dto';

// Packing and moving boxes is floor work, so the same roles that put stock away
// may do it. Reads are open to any signed-in user, like the other location
// screens. Every endpoint is warehouse-scoped in the service.
const PACK_ROLES = [
  UserRole.SYSTEM_ADMIN, UserRole.WAREHOUSE_MANAGER, UserRole.WAREHOUSE_SUPERVISOR, UserRole.WAREHOUSE_STAFF,
] as const;

@ApiTags('Containers')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard)
@Controller('containers')
export class ContainersController {
  constructor(private readonly service: ContainersService) {}

  @Get()
  @ApiOperation({ summary: 'Boxes, newest code order, with where they are and how much is in them' })
  list(
    @Query('warehouseId') warehouseId: string | undefined,
    @Query('slotId') slotId: string | undefined,
    @Query('search') search: string | undefined,
    @Query('includeEmpty') includeEmpty: string | undefined,
    @CurrentUser() user: any,
  ) {
    return this.service.list(
      { warehouseId: warehouseId || undefined, slotId: slotId || undefined, search: search || undefined, includeEmpty: includeEmpty !== 'false' },
      user,
    );
  }

  // Literal path first: "by-code" must not be read as an id.
  @Get('by-code/:code')
  @ApiOperation({ summary: 'What the scanner reads from BOX|<code>' })
  byCode(@Param('code') code: string) {
    return this.service.byCode(code);
  }

  @Get(':id')
  @ApiOperation({ summary: 'One box: contents, the boxes inside it, and where it came from' })
  get(@Param('id') id: string) {
    return this.service.get(id);
  }

  @Post() @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Make a box. The code (BOX-000123) is generated by the API.' })
  create(@Body() dto: CreateContainerDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.create(dto, userId, user);
  }

  @Patch(':id') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Rename a box, change its type, or seal / unseal it' })
  update(@Param('id') id: string, @Body() dto: UpdateContainerDto, @CurrentUser('id') userId: string) {
    return this.service.update(id, dto, userId);
  }

  @Post(':id/move') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Move the box to a slot — the stock inside, and any boxes inside it, move with it' })
  move(@Param('id') id: string, @Body() dto: MoveContainerDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.move(id, dto, userId, user);
  }

  @Post(':id/pack') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Pack stock into the box (the rows take the box’s location)' })
  pack(@Param('id') id: string, @Body() dto: PackItemsDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.packItems(id, dto, userId, user);
  }

  @Post(':id/unpack') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Take stock out of the box. It stays in the same slot.' })
  unpack(@Param('id') id: string, @Body() dto: PackItemsDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.unpackItems(id, dto, userId, user);
  }

  @Post(':id/split') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Split: a new box in the same place takes the rows chosen, and remembers where it came from' })
  split(@Param('id') id: string, @Body() dto: SplitContainerDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.split(id, dto, userId, user);
  }

  @Post(':id/merge') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Merge another box into this one' })
  merge(@Param('id') id: string, @Body() dto: MergeContainerDto, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.merge(id, dto, userId, user);
  }

  @Delete(':id') @UseGuards(RolesGuard) @Roles(...PACK_ROLES)
  @ApiOperation({ summary: 'Retire an empty box' })
  remove(@Param('id') id: string, @CurrentUser('id') userId: string, @CurrentUser() user: any) {
    return this.service.remove(id, userId, user);
  }
}
